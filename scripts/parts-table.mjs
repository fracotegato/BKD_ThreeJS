// Writes PART-NUMBERS.md from src/parts-numbers.js: every modelled part with its part numbers, by system.
// Run with `npm run numbers` after changing the numbers. `--check` only reports whether the file is up to date.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { PARTS, SYSTEMS } from '../src/parts-data.js';

const FILE = new URL('../PART-NUMBERS.md', import.meta.url);
const ids = Object.keys(PARTS);
const done = ids.filter((id) => PARTS[id].pn), none = ids.filter((id) => PARTS[id].noPn);
const open = ids.filter((id) => !PARTS[id].pn && !PARTS[id].noPn);
const source = (r) => (r.src === 'etka' ? `ETKA ${r.etka}${r.item ? `, item ${r.item}` : ''}` : 'Parts listing');

let out = `# Part numbers

Generated by \`npm run numbers\` from \`src/parts-numbers.js\`. Do not edit this file by hand.

- **ETKA** rows were read in the manufacturer's parts catalogue for the Golf 2004–2005 (illustration and item given).
- **Parts listing** rows come from sellers' listings and were not checked in the catalogue.
- Numbers change with build date, engine code and equipment. Check against the vehicle before ordering anything.

${ids.length} modelled parts: ${done.length} with a number, ${none.length} that have none of their own, ${open.length} still to be looked up.
`;
for (const [sys, s] of Object.entries(SYSTEMS)) {
  const rows = [];
  for (const id of ids.filter((k) => PARTS[k].sys === sys)) {
    const p = PARTS[id];
    if (p.pn) p.pn.forEach((r, i) => rows.push(`| ${i ? '' : p.name} | \`${r.n}\`${r.alt ? ` (also ${r.alt.map((a) => `\`${a}\``).join(', ')})` : ''} | ${r.what}${r.note ? `. ${r.note}` : ''} | ${r.qty} | ${source(r)} |`));
    else rows.push(`| ${p.name} | | ${p.noPn ? `No number of its own: ${p.noPn}` : 'Not looked up yet'} | | |`);
  }
  if (rows.length) out += `\n## ${s.name}\n\n| Part in the model | Number | Catalogue item | Qty | Source |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`;
}

if (process.argv.includes('--check')) {
  const same = existsSync(FILE) && readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n') === out;
  console.log(same ? 'PART-NUMBERS.md is up to date' : 'PART-NUMBERS.md is out of date: run npm run numbers');
  process.exit(same ? 0 : 1);
}
writeFileSync(FILE, out);
console.log(`PART-NUMBERS.md written: ${done.length} of ${ids.length} parts with a number, ${open.length} still to be looked up`);
